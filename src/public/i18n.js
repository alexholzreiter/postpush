const germanServerPatterns = [
  [/^Unavailable AirPlay outputs: (.+)$/, "Nicht erreichbare AirPlay-Ausgänge: $1"],
  [/^Could not subscribe to the MQTT topic: (.+)$/, "MQTT-Topic konnte nicht abonniert werden: $1"],
  [/^Could not start the web server: (.+)$/, "Webserver konnte nicht gestartet werden: $1"],
  [/^Speech generation failed (.+)$/, "Sprachausgabe fehlgeschlagen $1"],
];

export function localizeServerMessage(language, message) {
  if (language !== "de" || !message || message === "–") return message;
  if (germanServerMessages.has(message)) return germanServerMessages.get(message);
  for (const [pattern, replacement] of germanServerPatterns) {
    if (pattern.test(message)) return message.replace(pattern, replacement);
  }
  return message;
}
